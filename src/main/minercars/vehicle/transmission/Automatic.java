package minercars.vehicle.transmission;

/**
 * Automatic transmission.
 */
public class Automatic extends Transmission {

    /**
     * Creates an automatic transmission.
     */
    public Automatic() {
    }

    /**
     * Returns the display name {@code "Automatic"}.
     *
     * @return {@code "Automatic"}
     */
    @Override
    public String getName() {
        return "Automatic";
    }
}
