package minercars.vehicle.fuel;

/**
 * Diesel fuel type.
 */
public class Diesel extends Fuel {

    /**
     * Creates a diesel fuel type.
     */
    public Diesel() {
    }

    /**
     * Returns the display name {@code "Diesel"}.
     *
     * @return {@code "Diesel"}
     */
    @Override
    public String getName() {
        return "Diesel";
    }
}
